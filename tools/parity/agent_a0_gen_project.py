# ── документальные генераторы ─────────────────────────────────────────────
def add_docx_paragraphs(path: str, title: str, paragraphs: list[str], table: list[list[str]] | None = None) -> None:
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.add_heading(title, level=1)
    for text in paragraphs:
        if text.startswith("## "):
            doc.add_heading(text[3:], level=2)
        else:
            para = doc.add_paragraph(text)
            para.style.font.size = Pt(11)
    if table:
        doc.add_paragraph("Таблица 1. Реестр")
        doc_table = doc.add_table(rows=1, cols=len(table[0]))
        doc_table.style = "Table Grid"
        for index, value in enumerate(table[0]):
            doc_table.rows[0].cells[index].text = value
        for row in table[1:]:
            cells = doc_table.add_row().cells
            for index, value in enumerate(row):
                cells[index].text = str(value)
    # свойства документа: автор и организация (для проверки scrub_metadata)
    props = doc.core_properties
    props.author = PEOPLE["rp_customer"]
    props.company = CUSTOMER_SHORT
    props.title = title
    doc.save(path)


def add_xlsx(path: str, title: str, header: list[str], rows: list[list[str]]) -> None:
    from openpyxl import Workbook
    from openpyxl.styles import Font

    book = Workbook()
    sheet = book.active
    sheet.title = title[:31]
    sheet.append(header)
    for cell in sheet[1]:
        cell.font = Font(bold=True)
    for row in rows:
        sheet.append(row)
    for column, width in zip("ABCDEFGH", [14, 60, 20, 18, 18, 18, 18, 18]):
        sheet.column_dimensions[column].width = width
    book.save(path)


def add_pdf(path: str, title: str, paragraphs: list[str]) -> None:
    import pymupdf

    doc = pymupdf.open()
    page = doc.new_page()
    y = 60
    page.insert_text((50, y), title, fontsize=16, fontname="helv")
    y += 30
    for text in paragraphs:
        # helv не содержит кириллицу — используем встроенный "china-s"? нет:
        # PyMuPDF 1.28 умеет подставлять шрифт по имени файла; для кириллицы
        # берём системный Arial.
        for line in wrap_text(text, 95):
            page.insert_text((50, y), line, fontsize=10, fontname="arial", fontfile=ARIAL)
            y += 14
        y += 6
        if y > 780:
            page = doc.new_page()
            y = 60
    doc.save(path)
    doc.close()


def wrap_text(text: str, width: int) -> list[str]:
    words = text.split()
    lines, line = [], ""
    for word in words:
        if len(line) + len(word) + 1 > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    if line:
        lines.append(line)
    return lines


