"""Исправление «слипшихся» ФИО перед анонимизацией (pre-NER).

NER-модель и regex-слой не находят фамилию в записи «ВолодинВ.В.» —
между фамилией и инициалами нет границы. Модуль чинит такие записи
ДО передачи текста в NER («ВолодинВ.В.» → «Володин В. В.»).

Требование владельца: исправления вносятся в исходный файл ДО
анонимизации, чтобы NER увидел фамилию (см. handlers.anonymize —
исправленный текст подставляется в parsed.text и перезаписывается
в исходник атомарно, до вызова NER).

Осознанные ограничения:
* только кириллица (латиницей записанные имена не чинятся);
* только формы «ФамилияИ.О.» и «И.О.Фамилия» — произвольные слипания
  («ВолодинИванов») не диагностируются;
* исправление — только ВСТАВКА пробелов, буквы не меняются, поэтому
  ложное срабатывание максимум «разлипает» корректную запись.
"""
from __future__ import annotations

import re

# Однобуквенные классы: заглавные/строчные кириллические (ё отдельно —
# вне диапазона а-я в Unicode)
_UPPER = "А-ЯЁ"
_LOWER = "а-яё"
_SPACE = "[ \u00A0]?"  # между инициалами: ничего, пробел или nbsp

# Фамилия (возможно двойная через дефис)
_SURNAME = rf"[{_UPPER}][{_LOWER}]+(?:-[{_UPPER}][{_LOWER}]+)?"

# «ВолодинВ.В.» / «ВолодинВ. В.» → «Володин В. В.»: инициалы прилегают
# к фамилии ВПРИТЫК. Lookbehind отсекает продолжение слова (матч не
# может начинаться внутри другого слова). Уже корректные записи
# («Володин В.В.», «Володин В. В.») не матчатся: между фамилией и
# первой initial есть пробел, а фамилия короче двух букв не бывает.
_RE_SURNAME_FIRST = re.compile(
    rf"(?<![A-Za-zА-Яа-яЁё])"
    rf"({_SURNAME})"          # 1: фамилия
    rf"([{_UPPER}])\."        # 2: первая инициал
    rf"({_SPACE})"            # 3: возможный пробел между инициалами
    rf"([{_UPPER}])\."        # 4: вторая инициал
)

# «В.В.Володин» / «В. В.Володин» → «В. В. Володин»: фамилия прилегает
# к инициалам ВПРИТЫК. Lookbehind запрещает букву И точку перед первым
# инициалом: «А.Б.В.Гагарин» (две инициала + capitalized слово) не
# должно частично «разлипаться», «см.В.В.Путин» не трогаем.
_RE_INITIALS_FIRST = re.compile(
    rf"(?<![A-Za-zА-Яа-яЁё.])"
    rf"([{_UPPER}])\."        # 1: первая инициал
    rf"({_SPACE})"            # 2: возможный пробел между инициалами
    rf"([{_UPPER}])\."        # 3: вторая инициал
    rf"({_SURNAME})"          # 4: фамилия (прилегает впритык ко 2-й точке)
)


def _fix_surname_first(m: re.Match) -> str:
    return f"{m.group(1)} {m.group(2)}. {m.group(4)}."


def _fix_initials_first(m: re.Match) -> str:
    return f"{m.group(1)}. {m.group(3)}. {m.group(4)}"


def fix_glued_full_names(text: str) -> tuple[str, int]:
    """Исправить «слипшиеся» ФИО в тексте.

    Args:
        text: Исходный текст (parsed.text).

    Returns:
        Кортеж (исправленный текст, число исправлений). Переносы строк
        не вставляются и не удаляются — сегментация parsed.text по '\\n'
        остаётся согласованной с обратной сборкой файла.
    """
    if not text:
        return text, 0
    text, n1 = _RE_SURNAME_FIRST.subn(_fix_surname_first, text)
    text, n2 = _RE_INITIALS_FIRST.subn(_fix_initials_first, text)
    return text, n1 + n2
