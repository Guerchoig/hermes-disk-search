//! Правила агента (TR-3.8, TR-3.8a): `privacy.md` и `1c-domain.md`.
//!
//! Файлы кладутся в `<P>\agent-config\rules\` при каждом старте проекта. Они
//! **не содержат** путей пользователя, имён проектов и значений сущностей —
//! только синтаксис меток и порядок работы. Тексты одинаковы для всех проектов;
//! подстановка чего-либо из окружения запрещена (иначе правило утечёт).

/// Правила приватности: метки, документы Office, чтение образов.
pub const PRIVACY_MD: &str = r#"# Правила приватности (hds)

Ты работаешь в анонимной зоне. Всё, что ты видишь, уже обезличено: реальные
значения заменены метками вида `[PERSON_1]`, `[ORG_2]`, `[SYS_1]`, `[IMAGE_3]`.

## Метки

* Метка — это ссылка на значение, а не текст. Не переводи её, не склоняй
  вручную и не «расшифровывай»: пиши ровно как есть, включая падежный
  суффикс — `[PERSON_1|дат]`.
* Не придумывай значения вместо меток и не заменяй их на «Иванов», «ООО
  Ромашка» и подобное: это утечка и искажение.
* Если метка неизвестна (её нет в документе), оставь её как есть и скажи об
  этом в ответе.

## Документы

* `docx`, `xlsx` — только через инструменты `office_read`, `office_edit`,
  `office_create`. Инструмент `editor` для них запрещён.
* `*.pdf.md`, `*.pptx.md`, `*.mpp.md` — только чтение. Правки в них не
  вносятся; если нужна правка, создай новый документ.
* Правка существующего документа = правка его образа в рабочем каталоге.
  Оригинал пользователя не меняется.

## Пути

* Работай только внутри рабочего каталога проекта. Абсолютные пути вне его,
  UNC-пути, `\\?\`, `\\\\.\\`, альтернативные потоки (`file.txt:hidden`) и имена
  устройств (`CON`, `NUL`, `COM1`) запрещены.
* Относительные пути разрешены и считаются от корня рабочего каталога.

## Инструменты

* `run_commands` и `fetch_web_content` выключены. Вопрос пользователю задаётся
  только через `ask_user`.
* `apply_patch`, `ask_question`, `submit_and_exit` недоступны.
"#;

/// Доменные правила 1С и выбор инструмента поиска (TR-3.8a).
pub const DOMAIN_MD: &str = r#"# Предметная область и поиск (hds)

Ты помогаешь по проектам внедрения 1С:Предприятие: учёт, документы, требования,
сроки, роли. Ниже — как искать и когда какой инструмент использовать.

## Выбор инструмента поиска

1. Точная строка, номер договора, метка, имя объекта метаданных — `search_local_files`
   по точной подстроке или `search_local_files` с `kinds`. Не читай весь каталог.
2. «Где говорится о…», «какие есть…», «найди все…» — `search_local_files`
   несколькими формулировками (русский, английский, синонимы, транслит), разными
   `kinds` и `limit` 15–30. Объединяй найденное в ответ.
3. Нужен фрагмент внутри найденного файла — `office_read` для `docx`/`xlsx`,
   `read_files` для текстовых.
4. Вопрос по типовой функциональности 1С, БСП, лицензированию, стандартам
   разработки — `1c-buddy` (инструменты сервера `1c-buddy`).
5. Внешние сведения, которых нет в проекте, — `tavily`.

## Правила ответа

* Указывай путь файла и, если есть, страницу или таймкод.
* Не выдавай неполную выборку за полную: если поиск вернул мало, скажи об этом.
* Не пересказывай весь документ, если спросили про фрагмент.
* В вопросах про 1С указывай конфигурацию и версию платформы, если они известны.
"#;

/// Имя файла правил приватности.
pub const PRIVACY_FILE: &str = "privacy.md";
/// Имя файла доменных правил.
pub const DOMAIN_FILE: &str = "1c-domain.md";

/// Записать оба файла правил в каталог (создаётся при необходимости).
pub fn write_rules(dir: &std::path::Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dir)?;
    std::fs::write(dir.join(PRIVACY_FILE), PRIVACY_MD)?;
    std::fs::write(dir.join(DOMAIN_FILE), DOMAIN_MD)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rules_do_not_contain_user_paths() {
        for text in [PRIVACY_MD, DOMAIN_MD] {
            assert!(!text.contains("C:\\Users"), "путь пользователя в правилах");
            assert!(!text.contains("DESKTOP-"), "имя компьютера в правилах");
            assert!(!text.contains("P0001"), "имя проекта в правилах");
        }
    }

    #[test]
    fn rules_mention_key_requirements() {
        assert!(PRIVACY_MD.contains("office_read"));
        assert!(PRIVACY_MD.contains("office_edit"));
        assert!(PRIVACY_MD.contains("run_commands"));
        assert!(PRIVACY_MD.contains("ask_user"));
        assert!(DOMAIN_MD.contains("search_local_files"));
        assert!(DOMAIN_MD.contains("1c-buddy"));
        assert!(DOMAIN_MD.contains("tavily"));
    }

    #[test]
    fn write_rules_creates_both_files() {
        let dir = std::env::temp_dir().join(format!("hds-agent-rules-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        write_rules(&dir).unwrap();
        assert!(dir.join(PRIVACY_FILE).is_file());
        assert!(dir.join(DOMAIN_FILE).is_file());
        let _ = std::fs::remove_dir_all(&dir);
    }
}
