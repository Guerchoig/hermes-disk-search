//! `hds clip-index` — **заглушка B7**: CLIP переезжает в Rust на ONNX в W3
//! (`MIGRATION_PLAN_RUST.md` §7), поэтому дозаполнение CLIP-векторов картинок
//! здесь ещё недоступно.
//!
//! Поведение осознанно отличается от Python (`cmd_clip_index` вернул бы `1` при
//! недоступном CLIP): до W3 отправляем пользователя в Python-версию и возвращаем 1
//! (условный «не сделано»).

/// `cmd_clip_index`: сообщение + код 1 (как при недоступном CLIP в Python).
pub fn cmd_clip_index() -> i32 {
    println!("[--] CLIP ещё не перенесён в Rust (задача W3, §7 плана): \
              дозаполнение CLIP-векторов недоступно");
    println!("     До W5 используйте Python-версию: python -m hds.cli clip-index");
    1
}
